"""Deferred synthetic STEP -> profile -> frozen file-job contract cases.

Importing this module does not import FreeCAD, generate geometry, read CAD or
run any job. --generate is ONLY for a separately supervised, source-frozen
synthetic generation stage. The main campaign owns byte freeze, process limits,
exclusive records and the one permitted execution of each generated file job.
"""
from __future__ import annotations

import argparse
import hashlib
import importlib.util
import json
import math
from pathlib import Path


ROOT = Path(__file__).resolve().parents[1]
FIXTURE_SOURCE = ROOT / "tests" / "test_vendor_manufacturing_freecad_native.py"
FIXTURE_SHA256 = "5f1bbb3adb141bd829a3a4275ccecb10c21d58004758c89345be952da3579b66"
MAX_GENERATED_STEP_BYTES = 5_000_000
ANALYTICAL_AREA_TOL_MM2 = 1e-5  # Synthetic numerical oracle, not shop tolerance.


def _fixtures():
    raw = FIXTURE_SOURCE.read_bytes()  # Named source only, never a CAD fixture.
    if hashlib.sha256(raw).hexdigest() != FIXTURE_SHA256:
        raise ValueError("SYNTHETIC_FIXTURE_SOURCE_PIN_MISMATCH")
    spec = importlib.util.spec_from_file_location("pinned_file_workflow_synthetic_builders", FIXTURE_SOURCE)
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


def _profile(case_id, thickness):
    # Every compensation input is explicit and synthetic. A mathematical K
    # value and evidence hash absence are not material/process qualification.
    return {
        "schema": "SHERMAN_COMPENSATION_PROFILE_V1", "profile_id": f"synthetic-{case_id}-ansi-k04",
        "revision": "1", "material": "SYNTHETIC_ONLY_NOT_SHOP_MATERIAL",
        "process": "SYNTHETIC_ANALYTICAL_DEVELOPMENT", "tooling": "NO_QUALIFIED_TOOLING",
        "thickness_mm": float(thickness), "k_factor_ansi": 0.4,
        "inner_radius_min_mm": 1.0, "inner_radius_max_mm": 10.0,
        "sweep_min_deg": 1.0, "sweep_max_deg": 175.0,
        "evidence_sha256": None, "purpose": "synthetic_development",
    }


def create_cases(tempdir):
    """Lazily export four fresh synthetic STEP files; never run file jobs.

    Root indexes are deliberately absent. STEP roundtrip may change native face
    order; the controlled job selects its CAD-only default largest planar root.
    The receiving campaign must freeze the exact generated bytes independently.
    """
    folder = Path(tempdir).resolve()
    folder.mkdir(parents=True, exist_ok=True)
    if not folder.is_dir() or any(folder.iterdir()):
        raise ValueError("FRESH_EMPTY_SYNTHETIC_GENERATION_DIRECTORY_REQUIRED")
    builders = _fixtures()
    import FreeCAD as App

    allowance_l = math.pi / 2 * (2.0 + 0.4 * 1.5)
    area_l = 40.0 * (50.0 + allowance_l) - math.pi
    allowance_u = math.pi / 2 * (4.0 + 0.4 * 1.0)
    area_u = 20.0 * (60.0 + 2.0 * allowance_u)
    shape_l = builders._angled_l_shape(90.0, hole=True)
    shape_u = builders._u_shape()
    posed_source = builders._angled_l_shape(90.0, hole=True)
    placement = App.Placement(App.Vector(43.0, -21.0, 15.0), App.Rotation(App.Vector(1.0, 2.0, 3.0), 71.0))
    shape_posed = posed_source.transformed(placement.toMatrix())
    shape_sharp = builders._l_shape(sharp_return=True)
    definitions = [
        ("L90_hole", shape_l, 1.5, 1, area_l, "DRAFT_COMPUTED"),
        ("U90_two_bends", shape_u, 1.0, 2, area_u, "DRAFT_COMPUTED"),
        ("L90_hole_independent_pose", shape_posed, 1.5, 1, area_l, "DRAFT_COMPUTED"),
        ("sharp_return_refusal", shape_sharp, 1.0, 1, None, "UNAVAILABLE"),
    ]
    records = []
    for case_id, shape, thickness, count, area, status in definitions:
        if shape.ShapeType not in ("Solid", "Compound") or len(shape.Solids) != 1 or not shape.isValid():
            raise ValueError("INVALID_FRESH_SYNTHETIC_GENERATED_SOLID")
        if shape.ShapeType == "Compound":
            children = shape.childShapes()
            if (len(children) != 1 or children[0].ShapeType != "Solid"
                    or not children[0].isSame(shape.Solids[0])
                    or any(len(getattr(shape, name)) != len(getattr(shape.Solids[0], name))
                           for name in ("Faces", "Edges", "Vertexes"))):
                raise ValueError("EXTRANEOUS_SYNTHETIC_GENERATION_WRAPPER_TOPOLOGY")
        filename = f"synthetic-{case_id}.step"
        path = folder / filename
        if path.exists():
            raise ValueError("SYNTHETIC_STEP_OUTPUT_ALREADY_EXISTS")
        shape.exportStep(str(path))
        with path.open("rb") as stream:
            raw = stream.read(MAX_GENERATED_STEP_BYTES + 1)
        if not 0 < len(raw) <= MAX_GENERATED_STEP_BYTES:
            raise ValueError("GENERATED_SYNTHETIC_STEP_BYTE_BUDGET_EXCEEDED")
        records.append({"case_id": case_id, "step_filename": filename,
                        "source_sha256": hashlib.sha256(raw).hexdigest(),
                        "profile": _profile(case_id, thickness), "expected_bend_count": count,
                        "expected_area_mm2": area, "expected_status": status,
                        "expected_reason_prefix": "NATIVE_UNFOLD_REFUSED:" if status == "UNAVAILABLE" else None})
    return records


def assert_file_result(case, ledger):
    """Check a completed caller-owned job ledger; performs no I/O or native work."""
    assert type(case) is dict and type(ledger) is dict
    assert ledger["returncode"] == 0
    assert ledger["manufacturing_ready"] is False and ledger["cut_release_allowed"] is False
    result = ledger["result"]
    assert result["status"] == case["expected_status"]
    assert result["source_sha256"] == case["source_sha256"]
    profile_raw = json.dumps(case["profile"], sort_keys=True, separators=(",", ":"), allow_nan=False).encode()
    assert result["profile_sha256"] == hashlib.sha256(profile_raw).hexdigest()
    assert result["manufacturing_ready"] is False and result["cut_release_allowed"] is False
    if case["expected_status"] == "UNAVAILABLE":
        assert ledger["status"] == "UNAVAILABLE" and result["draft"] is None
        assert type(result["reason"]) is str and result["reason"]
        assert case["expected_reason_prefix"] == "NATIVE_UNFOLD_REFUSED:"
        assert result["reason"].startswith(case["expected_reason_prefix"])
        return
    assert case["expected_reason_prefix"] is None
    assert ledger["status"] == "COMPLETE_DRAFT"
    draft = result["draft"]
    assert draft["source_sha256"] == case["source_sha256"]
    assert draft["profile_sha256"] == result["profile_sha256"]
    assert draft["release_allowed"] is False and draft["manufacturing_ready"] is False
    assert draft["units"] == "mm" and draft["units_verified"] is True
    assert draft["source_units_are_not_physical_calibration"] is True
    assert result["source_unit_proof"]["source_sha256"] == case["source_sha256"]
    assert result["source_unit_proof"]["physical_calibration_verified"] is False
    count, area = case["expected_bend_count"], case["expected_area_mm2"]
    assert len(draft["bend_rows"]) == len(draft["bend_row_provenance"]) == len(draft["folded_bend_markers"]) == count
    proof = draft["coverage_proof"]
    assert proof["native_bend_count"] == count and proof["all_native_faces_accounted"] is True
    assert proof["all_native_bend_cylinders_paired"] is True
    assert abs(draft["flat_bounds"]["area_mm2"] - area) <= ANALYTICAL_AREA_TOL_MM2
    assert abs(proof["independent_neutral_area_mm2"] - area) <= ANALYTICAL_AREA_TOL_MM2
    coverage = [row["source_face_index"] for row in draft["source_face_coverage"]]
    assert len(coverage) == len(set(coverage)) == proof["native_face_count"]
    assert set(coverage) == set(range(proof["native_face_count"]))
    bridge = result["bend_id_bridge"]
    assert bridge["source_sha256"] == case["source_sha256"] and bridge["all_native_and_vendor_bends_bijective"] is True
    assert bridge["nominal_cad_identity_only"] is True and bridge["manufacturing_ready"] is False
    assignments = bridge["assignments"]
    assert len(assignments) == len({row["pair_id"] for row in assignments}) == len({row["feature_id"] for row in assignments}) == count
    mapping = {row["pair_id"]: row["feature_id"] for row in assignments}
    for row in draft["bend_row_provenance"] + draft["folded_bend_markers"]:
        assert row["feature_id"] == mapping[row["pair_id"]]
        assert row["vendor_feature_id_mapping"] == "SOURCE_BOUND_BIJECTION"
    assert draft["vendor_feature_id_mapping"] == "SOURCE_BOUND_BIJECTION"
    assert result["dxf_roundtrip"]["passed"] is True
    assert result["dxf_roundtrip"]["independent_importer_evidence"] is False
    assert result["dxf_roundtrip"]["physical_dimensions_verified"] is False
    from backend.vendor_manufacturing_dxf import read_analytic_dxf
    for name in ("cut_dxf", "bend_guide_dxf"):
        transport = result[name]
        assert transport["release_allowed"] is False and transport["manufacturing_ready"] is False
        decoded = read_analytic_dxf(transport["text"])
        assert decoded["units"] == "mm" and decoded["release_allowed"] is False
        assert abs(decoded["analytic_cut_area_mm2"] - area) <= ANALYTICAL_AREA_TOL_MM2
        bends = [row for row in decoded["rows"] if row["layer"] in ("BEND_UP", "BEND_DOWN")]
        assert len(bends) == (0 if name == "cut_dxf" else count)
        assert all(row["type"] == "LINE" for row in bends)
    assert result["release_gates"]["manufacturing_ready"] is False
    assert result["release_gates"]["cut_release_allowed"] is False
    json.dumps(result, allow_nan=False)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--generate", required=True, type=Path,
                        help="Fresh synthetic generation directory; does not freeze or run file jobs")
    args = parser.parse_args()
    records = create_cases(args.generate)
    with (args.generate / "generated-cases.json").open("x", encoding="utf-8") as stream:
        json.dump(records, stream, indent=2, allow_nan=False)
        stream.write("\n")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
