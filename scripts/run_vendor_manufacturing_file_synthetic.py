"""Two-phase generated STEP development protocol; no physical inputs.

Generate a fresh, frozen synthetic cohort under native caps. Then freeze the
exact generated bytes/profile/oracles and independently audit before execution.
Every record is exclusive and terminal; no retry/overwrite convenience exists.
"""
from __future__ import annotations

import argparse
from datetime import datetime, timezone
import fcntl
import hashlib
import importlib.util
import json
from pathlib import Path
import tempfile
import time

from backend import vendor_manufacturing_job as job

ROOT = job.ROOT
OWN_SOURCES = ("scripts/run_vendor_manufacturing_file_synthetic.py", "tests/test_vendor_manufacturing_file_native.py")
GEN_LIMITS = {**job.safety.LIMITS, "generated_case_limit": 4, "generated_total_bytes": 2_000_000}
EXPECTED_IDS = ("L90_hole", "U90_two_bends", "L90_hole_independent_pose", "sharp_return_refusal")


def pins():
    return {**job.source_pins(), **{name: job.safety._hash(ROOT / name) for name in OWN_SOURCES}}


def save_new(path, value):
    with Path(path).open("x", encoding="utf-8") as stream:
        json.dump(value, stream, indent=2, allow_nan=False)


def freeze_generation():
    return {"schema": "SHERMAN_SYNTHETIC_STEP_GENERATION_V1", "limits": GEN_LIMITS,
            "source_sha256": pins(), "inputs": "fresh_independently_constructed_shapes_only",
            "physical_inputs_read": False, "manufacturing_release_evidence": False}


def generate(frozen, directory, record_path):
    if frozen != freeze_generation():
        raise ValueError("GENERATION_FREEZE_MISMATCH")
    with open("/tmp/sherman-manufacturing-unfold.lock", "a") as lock:
        fcntl.flock(lock.fileno(), fcntl.LOCK_EX | fcntl.LOCK_NB)
        with record_path.open("x", encoding="utf-8") as stream:
            ledger = {"schema": "SHERMAN_SYNTHETIC_STEP_GENERATION_RUN_V1", "status": "RUNNING",
                "freeze": frozen, "started_at": datetime.now(timezone.utc).isoformat(),
                "peak_tree_rss_kib": 0, "manufacturing_ready": False, "cut_release_allowed": False,
                "returncode": None, "physical_inputs_read": False}
            job.safety._save(stream, ledger)
            started = time.monotonic()
            try:
                directory.mkdir(parents=False, exist_ok=False)
                with tempfile.TemporaryDirectory(prefix="sherman-step-generation-") as temp:
                    folder = Path(temp)
                    job._supervise_command([str(job.safety.RESOURCES / "bin/python"),
                        str(ROOT / "tests/test_vendor_manufacturing_file_native.py"), "--generate", str(directory.resolve())],
                        folder, started, ledger, job._environment(folder, native=True))
                if ledger["returncode"] != 0:
                    raise ValueError("SYNTHETIC_GENERATOR_FAILED")
                cases = load_cases(directory)
                if pins() != frozen["source_sha256"]:
                    raise ValueError("SOURCE_CHANGED_DURING_GENERATION")
                ledger.update(status="COMPLETE_SYNTHETIC_GENERATION", cases=cases)
            except BaseException as error:
                ledger.update(status="FAILED", error_type=type(error).__name__, reason=str(error)[:1000])
            finally:
                ledger.update(elapsed_seconds=time.monotonic() - started, finished_at=datetime.now(timezone.utc).isoformat())
                if ledger["elapsed_seconds"] > job.safety.MAX_SECONDS:
                    ledger.update(status="FAILED", reason="WALL_BUDGET_EXCEEDED")
                job.safety._save(stream, ledger)
            return ledger


def load_cases(directory):
    cases = job.safety._load_json(job._read_bounded(directory / "generated-cases.json", 200_000))
    if type(cases) is not list or not 0 < len(cases) <= GEN_LIMITS["generated_case_limit"]:
        raise ValueError("INVALID_GENERATED_CASE_SET")
    if [case.get("case_id") if type(case) is dict else None for case in cases] != list(EXPECTED_IDS):
        raise ValueError("COMPLETE_FROZEN_SYNTHETIC_CASE_ORDER_REQUIRED")
    ids, total = set(), 0
    for case in cases:
        fields = {"case_id", "step_filename", "source_sha256", "profile", "expected_bend_count", "expected_area_mm2", "expected_status", "expected_reason_prefix"}
        if type(case) is not dict or set(case) != fields:
            raise ValueError("INVALID_GENERATED_CASE_SCHEMA")
        name, case_id = case["step_filename"], case["case_id"]
        if (type(name) is not str or Path(name).name != name or not name.endswith(".step")
                or type(case_id) is not str or not 0 < len(case_id) <= 80 or case_id in ids
                or any(c not in "abcdefghijklmnopqrstuvwxyzABCDEFGHIJKLMNOPQRSTUVWXYZ0123456789_-" for c in case_id)):
            raise ValueError("INVALID_GENERATED_CASE_ID_OR_PATH")
        ids.add(case_id)
        path = directory / name
        if path.is_symlink():
            raise ValueError("SYNTHETIC_SOURCE_SYMLINK_REFUSED")
        raw = job._read_bounded(path, job.MAX_STEP_BYTES)
        total += len(raw)
        if hashlib.sha256(raw).hexdigest() != case["source_sha256"]:
            raise ValueError("GENERATED_CASE_HASH_MISMATCH")
        job._inputs(raw, case["source_sha256"], case["profile"], None, None)
        if case["profile"]["purpose"] != "synthetic_development" or case["expected_status"] not in {"DRAFT_COMPUTED", "UNAVAILABLE"}:
            raise ValueError("NOT_A_SYNTHETIC_ORACLE_CASE")
        if type(case["expected_bend_count"]) is not int or not 0 < case["expected_bend_count"] <= 32:
            raise ValueError("INVALID_BEND_COUNT_ORACLE")
        area = case["expected_area_mm2"]
        if case["expected_status"] == "DRAFT_COMPUTED" and (type(area) not in (int, float) or not 0 < area < 1e9):
            raise ValueError("INVALID_AREA_ORACLE")
        if case["expected_status"] == "UNAVAILABLE" and area is not None:
            raise ValueError("REFUSAL_CASE_MUST_NOT_HAVE_PARTIAL_AREA_ORACLE")
        if case["expected_reason_prefix"] != ("NATIVE_UNFOLD_REFUSED:" if case["expected_status"] == "UNAVAILABLE" else None):
            raise ValueError("NATIVE_GEOMETRY_REFUSAL_STAGE_REQUIRED")
    if total > GEN_LIMITS["generated_total_bytes"]:
        raise ValueError("GENERATED_TOTAL_BYTE_BUDGET_EXCEEDED")
    return cases


def generation_provenance(record_path, cases):
    raw = job._read_bounded(record_path, 2_000_000)
    receipt = job.safety._load_json(raw)
    if (type(receipt) is not dict or receipt.get("schema") != "SHERMAN_SYNTHETIC_STEP_GENERATION_RUN_V1"
            or receipt.get("status") != "COMPLETE_SYNTHETIC_GENERATION" or receipt.get("returncode") != 0
            or receipt.get("physical_inputs_read") is not False or receipt.get("cases") != cases
            or receipt.get("manufacturing_ready") is not False or receipt.get("cut_release_allowed") is not False
            or type(receipt.get("elapsed_seconds")) not in (int, float)
            or not 0 < receipt["elapsed_seconds"] <= job.safety.MAX_SECONDS
            or type(receipt.get("peak_tree_rss_kib")) is not int
            or not 0 < receipt["peak_tree_rss_kib"] <= job.safety.MAX_TREE_RSS_KIB):
        raise ValueError("COMPLETE_SOURCE_BOUND_GENERATION_RECEIPT_REQUIRED")
    freeze = receipt.get("freeze")
    if (type(freeze) is not dict or freeze.get("schema") != "SHERMAN_SYNTHETIC_STEP_GENERATION_V1"
            or freeze.get("limits") != GEN_LIMITS or freeze.get("physical_inputs_read") is not False
            or freeze.get("manufacturing_release_evidence") is not False
            or type(freeze.get("source_sha256")) is not dict
            or any(freeze["source_sha256"].get(name) != job.safety._hash(ROOT / name) for name in OWN_SOURCES)
            or freeze["source_sha256"].get("tests/test_vendor_manufacturing_freecad_native.py") != job.safety._hash(ROOT / "tests/test_vendor_manufacturing_freecad_native.py")):
        raise ValueError("GENERATION_SOURCE_PROVENANCE_MISMATCH")
    return {"record_path": str(record_path.resolve()), "record_sha256": hashlib.sha256(raw).hexdigest(),
            "source_sha256": freeze["source_sha256"], "synthetic_only": True}


def freeze_evaluation(directory, generation_record):
    cases = load_cases(directory)
    provenance = generation_provenance(generation_record, cases)
    jobs = [{"case": case, "freeze": job.freeze_file_job(
        job._read_bounded(directory / case["step_filename"], job.MAX_STEP_BYTES), case["source_sha256"], case["profile"])} for case in cases]
    return {"schema": "SHERMAN_SYNTHETIC_FILE_EVALUATION_V1", "source_sha256": pins(), "jobs": jobs,
            "generation_provenance": provenance,
            "selection": "all_generated_cases_in_retained_order", "area_oracle_error_limit_mm2": 1e-6,
            "limits": {"per_job": job.safety.LIMITS, "case_limit": 4, "total_wall_seconds": 510},
            "physical_inputs_read": False, "manufacturing_release_evidence": False}


def evaluate(frozen, directory, record_path, generation_record):
    if frozen != freeze_evaluation(directory, generation_record):
        raise ValueError("EVALUATION_FREEZE_MISMATCH")
    spec = importlib.util.spec_from_file_location("frozen_synthetic_file_oracles", ROOT / OWN_SOURCES[1])
    oracles = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(oracles)  # Stdlib only; import generates no native input.
    with record_path.open("x", encoding="utf-8") as stream:
        ledger = {"schema": "SHERMAN_SYNTHETIC_FILE_EVALUATION_RUN_V1", "status": "RUNNING", "freeze": frozen,
                  "cases": [], "started_at": datetime.now(timezone.utc).isoformat(),
                  "manufacturing_ready": False, "cut_release_allowed": False, "physical_inputs_read": False}
        job.safety._save(stream, ledger)
        started = time.monotonic()
        try:
            for entry in frozen["jobs"]:
                case = entry["case"]
                retained = {"case_id": case["case_id"], "passed": False, "reason": "NOT_EXECUTED"}
                ledger["cases"].append(retained)
                if time.monotonic() - started > frozen["limits"]["total_wall_seconds"] - job.safety.MAX_SECONDS:
                    retained["reason"] = "CAMPAIGN_WALL_BUDGET_EXCEEDED"
                    continue
                try:
                    raw = job._read_bounded(directory / case["step_filename"], job.MAX_STEP_BYTES)
                    target = record_path.with_name(record_path.stem + "-" + case["case_id"] + ".json")
                    result = job.run_file_job(raw, case["source_sha256"], case["profile"], entry["freeze"], target)
                    retained.update(record=str(target), record_sha256=job.safety._hash(target), actual_status=result["status"])
                    if result["status"] == "FAILED":
                        raise RuntimeError(result.get("reason") or "FILE_JOB_FAILED_WITHOUT_REASON")
                    oracles.assert_file_result(case, result)
                    envelope = result.get("result", {})
                    if case["expected_status"] == "UNAVAILABLE":
                        passed = (result["status"] == "UNAVAILABLE" and envelope.get("draft") is None
                                  and envelope.get("reason", "").startswith(case["expected_reason_prefix"]))
                    else:
                        draft = envelope.get("draft", {})
                        area = draft.get("flat_bounds", {}).get("area_mm2")
                        count = len(draft.get("bend_rows", []))
                        retained.update(actual_bend_count=count, actual_area_mm2=area)
                        passed = (result["status"] == "COMPLETE_DRAFT" and count == case["expected_bend_count"]
                                  and type(area) in (int, float) and abs(area - case["expected_area_mm2"]) <= frozen["area_oracle_error_limit_mm2"])
                    retained.update(passed=passed, reason="ORACLE_PASSED" if passed else envelope.get("reason", result.get("reason", "ORACLE_FAILED")))
                except Exception as error:
                    retained.update(reason=(str(error) or type(error).__name__)[:1000], exception_type=type(error).__name__)
                job.safety._save(stream, ledger)
            if pins() != frozen["source_sha256"]:
                raise ValueError("SOURCE_CHANGED_DURING_EVALUATION")
            ledger["status"] = "COMPLETE_SYNTHETIC" if all(case["passed"] for case in ledger["cases"]) else "FAILED"
        except BaseException as error:
            ledger.update(status="FAILED", reason=str(error)[:1000])
        finally:
            present = {row["case_id"] for row in ledger["cases"]}
            ledger["cases"].extend({"case_id": entry["case"]["case_id"], "passed": False, "reason": "NOT_EXECUTED_AFTER_FAILURE"}
                                   for entry in frozen["jobs"] if entry["case"]["case_id"] not in present)
            ledger.update(elapsed_seconds=time.monotonic() - started, finished_at=datetime.now(timezone.utc).isoformat())
            if ledger["elapsed_seconds"] > frozen["limits"]["total_wall_seconds"]:
                ledger.update(status="FAILED", reason="CAMPAIGN_WALL_BUDGET_EXCEEDED")
            job.safety._save(stream, ledger)
        return ledger


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--mode", choices=("freeze-generation", "generate", "freeze-evaluation", "evaluate"), required=True)
    parser.add_argument("--manifest", type=Path, required=True)
    parser.add_argument("--directory", type=Path)
    parser.add_argument("--record", type=Path)
    parser.add_argument("--generation-record", type=Path)
    args = parser.parse_args()
    if args.mode == "freeze-generation":
        save_new(args.manifest, freeze_generation()); return 0
    if args.directory is None:
        parser.error("directory is required")
    if args.mode == "freeze-evaluation":
        if args.generation_record is None:
            parser.error("generation-record is required for evaluation provenance")
        save_new(args.manifest, freeze_evaluation(args.directory, args.generation_record)); return 0
    if args.record is None:
        parser.error("record is required")
    frozen = job.safety._load_json(job._read_bounded(args.manifest, 2_000_000))
    if args.mode == "evaluate" and args.generation_record is None:
        parser.error("generation-record is required for evaluation provenance")
    result = generate(frozen, args.directory, args.record) if args.mode == "generate" else evaluate(frozen, args.directory, args.record, args.generation_record)
    print(json.dumps({key: result[key] for key in ("status", "elapsed_seconds")}))
    return 0 if result["status"].startswith("COMPLETE_") else 1


if __name__ == "__main__":
    raise SystemExit(main())
