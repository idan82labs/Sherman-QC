const STORAGE_KEY = 'sherman.vendorSetup.language'
export const VENDOR_LANGUAGE_EVENT = 'sherman-vendor-language-change'

export function readVendorLanguage(fallback?: VendorLanguage): VendorLanguage {
  try {
    const stored = window.localStorage.getItem(STORAGE_KEY)
    if (stored === 'en' || stored === 'he') return stored
  } catch { /* Storage can be unavailable in a locked-down kiosk. */ }
  return fallback || (navigator.language.toLowerCase().startsWith('he') ? 'he' : 'en')
}

export function persistVendorLanguage(language: VendorLanguage): void {
  try { window.localStorage.setItem(STORAGE_KEY, language) } catch { /* Keep the live choice. */ }
  window.dispatchEvent(new CustomEvent(VENDOR_LANGUAGE_EVENT, { detail: language }))
}
