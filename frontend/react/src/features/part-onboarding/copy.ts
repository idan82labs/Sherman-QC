export function reasonFor(code: string, language: OnbLanguage, serverMessage?: string): Reason & { code: string; known: boolean } {
  const entry = (reasonCopy as Record<string, Record<OnbLanguage, Reason>>)[code]
  if (entry) return { ...entry[language], code, known: true }
  return language === 'he'
    ? { title: serverMessage || 'בעיה שלא מוכרת לאשף.', action: 'דווחו עם הקוד ומספר החלק.', code, known: false }
    : { title: serverMessage || 'An issue this wizard does not recognise.', action: 'Report it with the code and the part number.', code, known: false }
}
